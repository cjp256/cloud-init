#!/bin/bash
# Tests for tools/generate-stable-netplan.sh
#
# Each scenario fully specifies its input topology (a synthetic
# /sys/class/net tree) and its full expected rendered netplan
# output. The actual rendered output is compared verbatim against
# the expected output (the timestamp on the first comment line is
# normalized to a fixed placeholder).
#
# Run: bash tests/test-generate-stable-netplan.sh

set -eu

SCRIPT_DIR=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=../tools/generate-stable-netplan.sh
. "${SCRIPT_DIR}/tools/generate-stable-netplan.sh"

PASS=0
FAIL=0

# make_nic <root> <ifname> <mac> <driver> [master_ifname] [dev_port] [shared_device]
#   - master_ifname: if set, create <ifname>/master -> ../<master_ifname>
#     (used to mark transparent VFs).
#   - dev_port: integer written to <ifname>/dev_port (default unset,
#     which the script treats as 0).
#   - shared_device: if set, <ifname>/device symlinks to
#     <root>/devices/<shared_device> instead of a private dir. Use to
#     simulate multi-port NICs where two interfaces share a parent
#     PCI device and are disambiguated only by dev_port (e.g. ens1
#     and ens1d1 on Azure mana NICs).
make_nic() {
    local root=$1 ifname=$2 mac=$3 driver=$4
    local master=${5:-} dev_port=${6:-} shared=${7:-}
    mkdir -p "${root}/${ifname}" "${root}/drivers/${driver}"
    if [ -n "${shared}" ]; then
        mkdir -p "${root}/devices/${shared}"
        ln -sf "../devices/${shared}" "${root}/${ifname}/device"
        ln -sf "../../drivers/${driver}" "${root}/devices/${shared}/driver"
    else
        mkdir -p "${root}/${ifname}/device"
        ln -sf "../../drivers/${driver}" "${root}/${ifname}/device/driver"
    fi
    echo "${mac}" > "${root}/${ifname}/address"
    echo 1        > "${root}/${ifname}/type"
    [ -n "${dev_port}" ] && echo "${dev_port}" > "${root}/${ifname}/dev_port"
    [ -n "${master}" ] && ln -sf "../${master}" "${root}/${ifname}/master"
}

make_lo() {
    local root=$1
    mkdir -p "${root}/lo"
    echo 00:00:00:00:00:00 > "${root}/lo/address"
    echo 772                > "${root}/lo/type"
}

# Header used by every expected output. Real output has a UTC
# timestamp on the first line; normalize_actual rewrites it to
# this fixed string before comparison.
HEADER='# Generated by generate-stable-netplan.sh on TIMESTAMP.
# Mirrors cloud-init PR #6807 (apply_network_config_set_name=false):
# enx<MAC> stanzas, MAC + driver match, no set-name (kernel keeps
# eth0/etc). Driver match is required to avoid binding to the AN VF.
network:
  version: 2
  renderer: networkd
  ethernets:'

normalize_actual() {
    sed -E 's/ on [0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:]+Z\./ on TIMESTAMP./'
}

# render_for <setup_fn>
#   Build the sysfs tree, run the script's pipeline, and print the
#   normalized rendered netplan to stdout.
render_for() {
    local setup_fn=$1 tmp nics primary
    tmp=$(mktemp -d)
    make_lo "${tmp}"
    "${setup_fn}" "${tmp}"
    nics=$(SYSFS_NET="${tmp}" enumerate_nics)
    primary=$(printf '%s\n' "${nics}" | pick_primary_mac)
    render_netplan "${primary}" "${nics}" | normalize_actual
    rm -rf "${tmp}"
}

# run_test <name> <setup_fn> <expected>
run_test() {
    local name=$1 setup_fn=$2 expected=$3 actual
    actual=$(render_for "${setup_fn}")
    if [ "${expected}" = "${actual}" ]; then
        PASS=$((PASS + 1))
        echo "ok  - ${name}"
    else
        FAIL=$((FAIL + 1))
        echo "FAIL - ${name}"
        diff <(printf '%s\n' "${expected}") <(printf '%s\n' "${actual}") \
            | sed 's/^/    /'
    fi
}

# ---- Scenarios -----------------------------------------------------

# 1 NIC, no AN -------------------------------------------------------
setup_1nic_no_an() {
    make_nic "$1" eth0 00:0d:3a:00:00:01 hv_netvsc
}
expected_1nic_no_an="${HEADER}
    enx000d3a000001:
      match:
        macaddress: 00:0d:3a:00:00:01
        driver: hv_netvsc
      dhcp4: true
      dhcp4-overrides:
        route-metric: 100
      dhcp6: false"

# 2 NICs, no AN ------------------------------------------------------
