# 2 NICs, mlx5 AN (each synthetic has an mlx5_core VF sibling) -------
setup_2nic_mlx_an() {
    make_nic "$1" eth0   00:0d:3a:00:00:01 hv_netvsc
    make_nic "$1" enP1s1 00:0d:3a:00:00:01 mlx5_core eth0
    make_nic "$1" eth1   00:0d:3a:00:00:02 hv_netvsc
    make_nic "$1" enP2s1 00:0d:3a:00:00:02 mlx5_core eth1
}
# VFs are filtered by the `master` symlink, so the rendered output
# is identical to the no-AN case — driver pinned to hv_netvsc.
expected_2nic_mlx_an="${expected_2nic_no_an}"

# 2 NICs, mana AN ----------------------------------------------------
setup_2nic_mana_an() {
    make_nic "$1" eth0   00:0d:3a:00:00:01 hv_netvsc
    make_nic "$1" enP1s1 00:0d:3a:00:00:01 mana eth0
    make_nic "$1" eth1   00:0d:3a:00:00:02 hv_netvsc
    make_nic "$1" enP2s1 00:0d:3a:00:00:02 mana eth1
}
expected_2nic_mana_an="${expected_2nic_no_an}"

# 2 NICs, mana-only (future SKU, no hv_netvsc) -----------------------
setup_2nic_mana_only() {
