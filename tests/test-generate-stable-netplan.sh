# 2 NICs, ens0 + ens0s1 ---------------------------------------------
# Regression: primary must be chosen by PCI device-path order, not
# by MAC. ens0 has the higher MAC but the lower PCI device number,
# so it must come first; ens0s1 must come second.
setup_2nic_ens_pci() {
    make_nic "$1" ens0   00:0d:3a:00:00:99 mana
    make_nic "$1" ens0s1 00:0d:3a:00:00:01 mana
}
expected_2nic_ens_pci="${HEADER}
    enx000d3a000099:
      match:
        macaddress: 00:0d:3a:00:00:99
        driver: mana
      dhcp4: true
      dhcp4-overrides:
        route-metric: 100
      dhcp6: false
    enx000d3a000001:
      match:
        macaddress: 00:0d:3a:00:00:01
        driver: mana
      dhcp4: true
      dhcp4-overrides:
        route-metric: 200
        use-dns: false
      dhcp6: false"

# 2 NICs, ens1 (dev_port 0) + ens1d1 (dev_port 1) -------------------
# Regression: a multi-port NIC where both interfaces share the same
# parent PCI device. The kernel disambiguates them only via
# dev_port; ens1 (dev_port 0, higher MAC) must be primary, ens1d1
# (dev_port 1) must be secondary. Mirrors a real Azure observation:
#   $ cat ens1/dev_port    -> 0
#   $ cat ens1d1/dev_port  -> 1
setup_2nic_ens_devport() {
    make_nic "$1" ens1   00:0d:3a:00:00:99 mana "" 0 mana_pf0
    make_nic "$1" ens1d1 00:0d:3a:00:00:01 mana "" 1 mana_pf0
}
expected_2nic_ens_devport="${HEADER}
    enx000d3a000099:
      match:
        macaddress: 00:0d:3a:00:00:99
        driver: mana
      dhcp4: true
      dhcp4-overrides:
        route-metric: 100
      dhcp6: false
    enx000d3a000001:
      match:
        macaddress: 00:0d:3a:00:00:01
        driver: mana
      dhcp4: true
      dhcp4-overrides:
        route-metric: 200
        use-dns: false
      dhcp6: false"

# ---- Run -----------------------------------------------------------

run_test "1 NIC, no AN"                   setup_1nic_no_an       "${expected_1nic_no_an}"
run_test "2 NICs, no AN"                  setup_2nic_no_an       "${expected_2nic_no_an}"
run_test "4 NICs, no AN"                  setup_4nic_no_an       "${expected_4nic_no_an}"
run_test "2 NICs, mlx5 AN (VFs filtered)" setup_2nic_mlx_an      "${expected_2nic_mlx_an}"
run_test "2 NICs, mana AN (VFs filtered)" setup_2nic_mana_an     "${expected_2nic_mana_an}"
run_test "2 NICs, mana-only"              setup_2nic_mana_only   "${expected_2nic_mana_only}"
run_test "2 NICs, ens0+ens0s1 PCI order"  setup_2nic_ens_pci     "${expected_2nic_ens_pci}"
run_test "2 NICs, ens1+ens1d1 dev_port"   setup_2nic_ens_devport "${expected_2nic_ens_devport}"

echo
echo "Passed: ${PASS}  Failed: ${FAIL}"
[ "${FAIL}" -eq 0 ]
